#   ③ 0.6 是本项目 7+ 任务（迷宫 / 女神 / 家园 / 导航…）长期沿用的实测值；
#   ④ 低于 0.5 易误点噪声文本，高于 0.7 已被上述两次真机证伪。
OCR_TARGET_CONF: float = 0.6

# 画面级多词 AND 判据：靠「多词同现」抗噪，允许更低下限；**不用于点按钮**。
# 长期真机验证过的下限，本轮刻意不动（抬到 0.6 会让低分结构词漏判）。
OCR_SCREEN_CONF: float = 0.5

# 安全关键：退出确认弹窗（点错 = 退出游戏）→ 保持高阈值 + 模板优先
OCR_QUIT_CONF: float = 0.8

# 右下角「家园」按钮：全等 + 坐标约束，与 screen_registry._has_home_btn 共用
OCR_HOME_BTN_CONF: float = 0.8
